// Generates src/abi.ts from contracts/abi/*.json. The ethers-exported JSON has stateMutability "undefined"
// for nonpayable functions and extra constant/payable keys; normalise them so viem accepts the ABI.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const abiDir = path.resolve(here, "../../../contracts/abi");
const norm = (abi) =>
  abi
    .filter((f) => ["function", "event", "error"].includes(f.type))
    .map((f) => {
      const o = { type: f.type, name: f.name };
      const fixIo = (x) => ({ type: x.type, name: x.name ?? "", ...(x.indexed !== undefined ? { indexed: x.indexed } : {}), ...(x.components ? { components: x.components.map(fixIo) } : {}) });
      o.inputs = (f.inputs ?? []).map(fixIo);
      if (f.type === "function") {
        o.outputs = (f.outputs ?? []).map(fixIo);
        o.stateMutability = ["view", "pure", "payable"].includes(f.stateMutability) ? f.stateMutability : "nonpayable";
      }
      if (f.type === "event") o.anonymous = false;
      return o;
    });
const read = (n) => JSON.parse(fs.readFileSync(path.join(abiDir, n), "utf8"));
const ex = norm(read("PerpExchange.merged.json"));
const usdc = norm(read("MockUSDC.json"));
const oracle = norm(read("ManualOracle.json"));
// custom errors that live in OZ/ERC20 and are not in the merged exchange ABI but can surface through the router
const errNames = new Set(ex.filter((f) => f.type === "error").map((f) => f.name));
const extraErrors = usdc.filter((f) => f.type === "error" && !errNames.has(f.name));
const body =
  `// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/abi/*.json. Do not edit.\n` +
  `export const exchangeAbi = ${JSON.stringify(ex, null, 2)} as const;\n\n` +
  `export const erc20Abi = ${JSON.stringify(usdc, null, 2)} as const;\n\n` +
  `export const manualOracleAbi = ${JSON.stringify(oracle, null, 2)} as const;\n\n` +
  `/** ERC20 custom errors (surface when deposit() pulls USDC). */\n` +
  `export const erc20ErrorsAbi = ${JSON.stringify(extraErrors, null, 2)} as const;\n`;
fs.writeFileSync(path.resolve(here, "../src/abi.ts"), body);
console.log("wrote src/abi.ts", { exchange: ex.length, erc20: usdc.length, oracle: oracle.length, extraErrors: extraErrors.length });
